#!/usr/bin/env python3
"""Assemble a pack into a self-contained skill folder for a marketplace.

    python3 scripts/build_pack.py packs/readable-errors dist/

Copies SKILL.md, references/, rules/, pack.yml and agensi.yml, the three schemas,
and writes scripts/moly_lite.py: the engine's modules concatenated into one file
so the skill runs with no install beyond PyYAML and jsonschema.
"""

from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODULES = ["rules", "check", "scan", "render", "cli"]


def build_lite() -> str:
    parts = ['"""moly_lite: the Moly engine in one file. Generated by scripts/build_pack.py. Do not edit."""',
             "from __future__ import annotations", ""]
    for name in MODULES:
        src = (ROOT / "moly" / f"{name}.py").read_text()
        src = re.sub(r"^from __future__ import annotations\n", "", src, flags=re.M)
        src = re.sub(r"^from moly\.\w+ import .*\n", "", src, flags=re.M)
        parts.append(f"# ---- moly/{name}.py ----")
        parts.append(src)
    body = "\n".join(parts)
    # The one-file build sits inside the pack, beside pack.yml; schemas are copied beside it.
    body = body.replace(
        'ROOT = Path(__file__).resolve().parent.parent\nSCHEMA_DIR = ROOT / "schema"',
        'ROOT = Path(__file__).resolve().parent.parent\nSCHEMA_DIR = ROOT / "schema"  # dist layout: <pack>/schema',
    )
    body += "\n\nif __name__ == '__main__':\n    raise SystemExit(main())\n"
    return body


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__)
        return 2
    pack_dir, out_root = Path(argv[1]), Path(argv[2])
    out = out_root / pack_dir.name
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    for item in ["SKILL.md", "pack.yml", "agensi.yml", "references", "rules"]:
        src = pack_dir / item
        if not src.exists():
            continue
        if src.is_dir():
            shutil.copytree(src, out / item)
        else:
            shutil.copy2(src, out / item)
    shutil.copytree(ROOT / "schema", out / "schema")
    (out / "scripts").mkdir()
    (out / "scripts" / "moly_lite.py").write_text(build_lite())
    files = sorted(p for p in out.rglob("*") if p.is_file())
    print(f"built {out} with {len(files)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
